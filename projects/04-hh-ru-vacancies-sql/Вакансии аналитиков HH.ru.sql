-- =============================================================================
-- 5. Требуемый опыт (грейд)
-- =============================================================================
SELECT experience,
       COUNT(*) AS vacancies
FROM public.parcing_table
GROUP BY experience
ORDER BY vacancies DESC;

--       experience       | vacancies
-- -----------------------+-----------
--  Junior+ (1-3 years)   |      1091
--  Middle (3-6 years)    |       555
--  Junior (no experience)|       142
--  Senior (6+ years)     |        13


-- 5.1. Доли грейдов только среди профильных вакансий
--      (в названии есть «аналитик данных» или «системный аналитик»)
WITH analyst_vacancies AS (
    SELECT *
    FROM public.parcing_table
    WHERE name ILIKE '%аналитик данных%'
       OR name ILIKE '%системный аналитик%'
)
SELECT experience,
       COUNT(*)                                            AS vacancies,
       ROUND(COUNT(*) * 100.0 / SUM(COUNT(*)) OVER (), 2) AS share_pct
FROM analyst_vacancies
GROUP BY experience
ORDER BY share_pct DESC;

--       experience       | vacancies | share_pct
-- -----------------------+-----------+-----------
--  Junior+ (1-3 years)   |       854 |     64.40
--  Middle (3-6 years)    |       345 |     26.02
--  Junior (no experience)|       121 |      9.13
--  Senior (6+ years)     |         6 |      0.45

-- Основной спрос — на Junior+ с опытом 1–3 года (64%). Позиций без опыта
-- всего ~9%: чтобы зайти в профессию, нужен хотя бы проектный опыт.
-- Senior-вакансий почти нет — таких специалистов, скорее всего, ищут
-- через рекомендации и хедхантинг, а не через открытые вакансии.


-- =============================================================================
-- 6. Типичный работодатель: условия и зарплаты
-- =============================================================================
SELECT employer,
       employment,
       schedule,
       COUNT(*)                   AS vacancies,
       ROUND(AVG(salary_from), 2) AS avg_salary_from,
       ROUND(AVG(salary_to), 2)   AS avg_salary_to
FROM public.parcing_table
WHERE name ILIKE '%аналитик данных%'
   OR name ILIKE '%системный аналитик%'
GROUP BY employer, employment, schedule
ORDER BY vacancies DESC;

--  employer        | employment       | schedule    | vacancies | avg_salary_from | avg_salary_to
-- -----------------+------------------+-------------+-----------+-----------------+--------------
--  СБЕР            | Полная занятость | Полный день |       117 |       110583.33 |      73333.33
--  Банк ВТБ (ПАО)  | Полная занятость | Полный день |        27 |                 |
--  Ozon            | Полная занятость | Полный день |        23 |                 |
-- ...

-- Типичная вакансия — крупная компания, полная занятость, полный день.
-- Зарплаты указывают далеко не все: у ВТБ и Ozon вилка не опубликована.
-- У СБЕРа средняя «до» ниже средней «от»: средние считаются по разным
-- подмножествам вакансий (где-то указана только нижняя граница, где-то
-- только верхняя), поэтому сравнивать их напрямую нельзя.


-- =============================================================================
-- 7. Ключевые навыки
-- =============================================================================
-- Навыки лежат в нескольких столбцах (key_skills_1..N, soft_skills_1..N);
-- ниже — пример для key_skills_1, для остальных столбцов запрос аналогичный.
SELECT key_skills_1,
       COUNT(*) AS mentions
FROM public.parcing_table
WHERE key_skills_1 IS NOT NULL
GROUP BY key_skills_1
ORDER BY mentions DESC;

--  key_skills_1   | mentions
-- ----------------+----------
--  Анализ данных  |      312
--  SQL            |      161
--  Документация   |       89
--  MS SQL         |       87
-- ...

-- В топе — «Анализ данных», SQL, «Документация» и MS SQL: работа с базами
-- данных — базовое требование, «Документация» характерна для системных
-- аналитиков.
-- Ограничение: запрос учитывает только первый навык в списке (key_skills_1),
-- поэтому Python и другие навыки, указанные дальше, здесь не видны. Чтобы
-- оценить их реальную долю, нужно посчитать упоминания по всем столбцам
-- key_skills_1..N.
-- Примечание: в ~380 вакансиях key_skills_1 не заполнен.
